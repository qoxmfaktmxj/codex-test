const assert = require('node:assert/strict');
const { scoreDice, createGame, rollDice, keepDice, bankPoints, resetGame } = require('./game-logic');

assert.equal(scoreDice([1]), 100);
assert.equal(scoreDice([5]), 50);
assert.equal(scoreDice([1,1,1]), 1000);
assert.equal(scoreDice([2,2,2]), 200);
assert.equal(scoreDice([2,3]), 0);
let game = createGame();
assert.deepEqual([game.total, game.turn, game.rolls], [0, '굴리기', 0]);
game = rollDice(game, [1,5,2,3,4,6]);
assert.equal(game.rolls, 1);
game = keepDice(game, [0,1]);
assert.deepEqual(game.kept, [1,5]);
assert.equal(game.turnPoints, 150);
game = rollDice(game, [1]);
game = keepDice(game, [0]);
assert.equal(game.turnPoints, 250);
game = bankPoints(game);
assert.equal(game.total, 250);
assert.equal(game.finished, false);
let invalidGame = rollDice(createGame(), [1,2,3,4,5,6]);
assert.throws(() => keepDice(invalidGame, [0,1]), /점수가 되는/);
game = { ...game, total: 950, turnPoints: 50, kept: [5] };
game = bankPoints(game);
assert.equal(game.finished, true);
assert.equal(game.total, 1000);
assert.deepEqual(resetGame(), createGame());
console.log('천점 주사위 세탁표 교환소 로직 테스트 통과');
