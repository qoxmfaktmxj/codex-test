const assert = require('node:assert/strict');
const { createGame, launch, step, flip, reset } = require('./game-logic.js');

let game = createGame(() => 0.5);
assert.equal(game.status, 'ready');
assert.equal(game.balls, 3);
game = launch(game);
assert.equal(game.status, 'playing');
assert.ok(game.ball.vy < 0);
game = flip(game, 'left');
assert.equal(game.flippers.left, true);
game = step(game, 16);
assert.equal(game.flippers.left, false);
game = { ...game, ball: { x: 165, y: 108, vx: 0, vy: 120 }, bumpers: [false, false, false] };
game = step(game, 16);
assert.equal(game.score, 100);
assert.equal(game.balls, 3);
game = { ...game, ball: { x: 165, y: 110, vx: 0, vy: 0 } };
game = step(game, 16);
const firstBumperScore = game.score;
game = { ...game, ball: { x: 165, y: 110, vx: 0, vy: 0 } };
game = step(game, 16);
assert.equal(game.score, firstBumperScore);
game = { ...game, ball: { x: 160, y: 510, vx: 0, vy: 100 }, balls: 1 };
game = step(game, 16);
assert.equal(game.status, 'over');
assert.equal(game.balls, 0);
assert.equal(reset(game).status, 'ready');
console.log('핀볼 로직 테스트 통과');
