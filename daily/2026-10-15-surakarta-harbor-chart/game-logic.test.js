const assert = require('node:assert/strict');
const { createGame, movePiece, legalMoves, reset } = require('./game-logic.js');
let game = createGame();
assert.equal(game.turn, 'navy');
assert.equal(game.board.filter(piece => piece === 'navy').length, 12);
assert.equal(legalMoves(game).some(move => move.from === 24 && move.to === 18), true);
game = movePiece(game, 24, 18);
assert.equal(game.board[18], 'navy');
assert.equal(game.turn, 'coral');
assert.equal(movePiece(game, 18, 19), game);
let capture = { ...createGame(), board: Array(36).fill(null), turn: 'navy' };
capture.board[1] = 'navy'; capture.board[12] = 'coral';
assert.equal(legalMoves(capture).some(move => move.from === 1 && move.to === 12 && move.capture), true);
assert.equal(legalMoves(capture).some(move => move.from === 1 && move.to === 2 && move.capture), false);
capture = movePiece(capture, 1, 12);
assert.equal(capture.board[12], 'navy');
assert.equal(capture.captured.navy, 1);
let win = { ...createGame(), board: Array(36).fill(null), turn: 'navy', captured: { navy: 11, coral: 0 } };
win.board[1] = 'navy'; win.board[12] = 'coral';
win = movePiece(win, 1, 12);
assert.equal(win.status, 'won');
assert.equal(win.winner, 'navy');
assert.equal(reset(win).captured.coral, 0);
