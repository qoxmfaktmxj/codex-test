const assert=require('node:assert/strict');
const {createGame,select,play,winningLines,players,resetGame}=require('./game-logic');
const [blue,terracotta]=players;
let game=createGame();
assert.equal(game.board.length,9);
assert.equal(game.turn,blue);
assert.equal(game.phase,'놓기');
game=play(game,0);
assert.equal(game.board[0],blue);
assert.equal(game.turn,terracotta);
game=play(game,4); game=play(game,2); game=play(game,5); game=play(game,3); game=play(game,7);
assert.equal(game.phase,'이동');
game={...createGame(),turn:blue,phase:'놓기',board:[blue,blue,null,terracotta,null,null,null,null,terracotta]};
game=play(game,2);
assert.equal(game.winner,blue);
assert.ok(winningLines.some(line=>line.join(',')==='0,1,2'));
game={...createGame(),phase:'이동',turn:blue,board:[blue,null,null,terracotta,blue,null,null,terracotta,terracotta]};
game=select(game,0); game=play(game,1);
assert.equal(game.board[1],blue);
assert.equal(game.board[0],null);
assert.deepEqual(resetGame(),createGame());
console.log('아치 도자기 창 로직 테스트 통과');
